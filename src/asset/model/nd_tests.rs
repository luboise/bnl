fn stream_test(offset: usize, nd_bytes: &[u8]) -> Result<(), Box<dyn std::error::Error>> {
    let zeroes = vec![0u8; offset];

    let input = zeroes
        .iter()
        .copied()
        .chain(nd_bytes.to_vec())
        .collect::<Vec<_>>();

    let mut read_cur = std::io::Cursor::new(&input);
    read_cur.seek(SeekFrom::Start(offset.try_into()?))?;

    let x = Default::default();

    let mrc = crate::asset::model::nd::ModelReadContext::new(&x, &[]);

    let nd = read_cur.read_le_args::<crate::asset::model::nd::Nd>(&mrc)?;

    let mut output = vec![];
    let mut write_cur = std::io::Cursor::new(&mut output);
    write_cur.write_all(&zeroes)?;

    write_cur.write_le(&nd)?;

    compare_streams(&input, &output);

    Ok(())
}

pub(crate) fn compare_streams(expected: &[u8], received: &[u8]) {
    for (i, (a, b)) in expected.iter().zip(received.iter()).enumerate() {
        assert_eq!(
            *a,
            *b,
            "mismatch at byte 0x{i:x}:\n{:x?}\n{:x?}",
            &expected[i - 3..i + 4],
            &received[i - 3..i + 4]
        );
    }
}

